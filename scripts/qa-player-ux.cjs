async (page) => {
  const context = await page.context().browser().newContext({ viewport: {width:1366, height:900} });
  const playerPage = await context.newPage();
  const results = [], errors = [];
  playerPage.on('pageerror', error => errors.push(error.message));
  const check = (name, pass) => results.push({name, pass: !!pass});
  try {
    await playerPage.goto('http://127.0.0.1:4173/#/title?title=spiderman-brand-new-day');
    check('film detail shows hours and minutes', /2 h 24 min/.test(await playerPage.locator('#app').innerText()));
    await playerPage.goto('http://127.0.0.1:4173/#/player?title=caminandes-2');
    check('one playback toggle initially offers play', await playerPage.locator('.player-toggle').getAttribute('aria-label') === 'Reproducir' && await playerPage.locator('.player-toggle').count() === 1);
    await playerPage.locator('.player-center-play').click();
    await playerPage.waitForFunction(() => document.querySelector('video').currentTime > .5 && !document.querySelector('video').paused);
    check('playing changes the same button to pause', await playerPage.locator('.player-toggle').getAttribute('aria-label') === 'Pausar');
    await playerPage.locator('.player-toggle').click();
    check('click pauses and restores play label', await playerPage.locator('video').evaluate(video => video.paused) && await playerPage.locator('.player-toggle').getAttribute('aria-label') === 'Reproducir');
    await playerPage.locator('#app').focus();
    await playerPage.keyboard.press('k');
    await playerPage.waitForFunction(() => !document.querySelector('video').paused);
    check('K works outside the player shell', await playerPage.locator('.player-toggle').getAttribute('aria-label') === 'Pausar');
    await playerPage.keyboard.press('Space');
    check('Space pauses from main focus', await playerPage.locator('video').evaluate(video => video.paused));
    const start = await playerPage.locator('video').evaluate(video => video.currentTime);
    await playerPage.keyboard.press('l');
    await playerPage.waitForFunction(before => document.querySelector('video').currentTime >= before + 9.9, start);
    check('L seeks forward and shows feedback', await playerPage.locator('.player-feedback').innerText() === '+10 s');
    await playerPage.keyboard.press('j');
    check('J seeks backward', await playerPage.locator('video').evaluate((video, before) => Math.abs(video.currentTime-before) < .2, start));
    await playerPage.keyboard.press('m');
    check('M mutes and updates accessible state', await playerPage.locator('video').evaluate(video => video.muted) && await playerPage.getByRole('button', {name:'Activar sonido', exact:true}).getAttribute('aria-pressed') === 'true');
    const volume = await playerPage.locator('video').evaluate(video => video.volume);
    await playerPage.keyboard.press('ArrowUp');
    check('Up increases actual volume', await playerPage.locator('video').evaluate((video, before) => Math.abs(video.volume - before - .05) < .001, volume));
    await playerPage.locator('input[aria-label="Volumen"]').focus();
    await playerPage.keyboard.press('k');
    check('range input keeps native keyboard interaction', await playerPage.locator('video').evaluate(video => video.paused));
    await playerPage.locator('video').click({position:{x:50,y:50}});
    await playerPage.waitForFunction(() => !document.querySelector('video').paused);
    check('clicking video toggles playback', await playerPage.locator('.player-toggle').getAttribute('aria-label') === 'Pausar');
    await playerPage.locator('video').click({position:{x:50,y:50}});
    await playerPage.locator('#app').focus();
    await playerPage.keyboard.press('f');
    await playerPage.waitForFunction(() => !!document.fullscreenElement);
    check('F enters fullscreen with controls', await playerPage.evaluate(() => document.fullscreenElement.classList.contains('player-shell')));
    await playerPage.keyboard.press('f');
    await playerPage.waitForFunction(() => !document.fullscreenElement);
    check('F exits fullscreen', await playerPage.evaluate(() => !document.fullscreenElement));
    await playerPage.goto('http://127.0.0.1:4173/#/player?title=spiderman-brand-new-day');
    await playerPage.locator('.player-center-play').click();
    await playerPage.waitForFunction(() => document.querySelector('video').duration > 8600);
    await playerPage.locator('.player-toggle').click();
    await playerPage.locator('video').evaluate(video => { video.currentTime = 3661; });
    await playerPage.waitForFunction(() => document.querySelector('.time').textContent.includes('1:01:01 / 2:24:38'));
    check('real long film playback uses hours', /1:01:01 \/ 2:24:38/.test(await playerPage.locator('.time').innerText()));
    check('seek exposes readable time for assistive technology', /1:01:01/.test(await playerPage.locator('input[aria-label="Progreso de reproducción"]').getAttribute('aria-valuetext')));
    await playerPage.locator('.player-toggle').focus();
    await playerPage.evaluate(() => scrollTo(0, 0));
    await playerPage.screenshot({path:'output/playwright/player-ux-hours.png', fullPage:true});
    return {total:results.length, passed:results.filter(item=>item.pass).length, failures:results.filter(item=>!item.pass), errors};
  } finally { await context.close(); }
}
